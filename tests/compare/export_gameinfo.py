def lua_string(s):
    out = ['"']
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ord(ch) < 32:
            out.append("\\%03d" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def lua_value(v, boolean):
    if boolean:
        return "true" if v else "false"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if v == int(v) and abs(v) < 2 ** 31:
            return str(int(v))
        return repr(v)
    if isinstance(v, bytes):
        v = v.decode("utf-8", "replace")
    return lua_string(str(v))


def export(db_path, out_path):
    con = sqlite3.connect("file:%s?mode=ro" % db_path, uri=True)
    have = {r[0] for r in con.execute("select name from sqlite_master where type='table'")}
    lines = ["-- Generated by tests/compare/export_gameinfo.py from %s. Do not commit." % os.path.basename(db_path),
             "return {"]
    missing = []
    for table in TABLES:
        if table not in have:
            missing.append(table)
            continue
        info = con.execute('pragma table_info("%s")' % table).fetchall()
        cols = [c[1] for c in info]
        booleans = {c[1] for c in info if (c[2] or "").upper() == "BOOLEAN"}
        pks = [c[1] for c in sorted(info, key=lambda c: c[5]) if c[5] > 0]
        pk = pks[0] if len(pks) == 1 else None
        rows = con.execute('select %s from "%s" order by rowid' % (",".join('"%s"' % c for c in cols), table)).fetchall()
        lines.append("%s = { pk = %s, rows = {" % (table, lua_string(pk) if pk else "nil"))
        for row in rows:
            fields = []
            for c, v in zip(cols, row):
                if v is None:
                    continue
                fields.append("%s=%s" % (c, lua_value(v, c in booleans)))
            lines.append("{" + ",".join(fields) + "},")
        lines.append("} },")
    lines.append("}")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return missing


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DEFAULT_DB)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()
    if not os.path.exists(args.db):
        print("no database at %s (load a game once to create it)" % args.db, file=sys.stderr)
        return 2
    missing = export(args.db, args.out)
    size = os.path.getsize(args.out)
    print("wrote %s (%.1f MB)" % (args.out, size / 1e6))
    if missing:
        print("not in this database: " + " ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
